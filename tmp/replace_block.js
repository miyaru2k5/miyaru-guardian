const fs = require('fs');
const path = 'components/admin/posts/PostsList.tsx';
let text = fs.readFileSync(path, 'utf8');
const startPattern = '    const payload = {';
const start = text.indexOf(startPattern);
if (start === -1) throw new Error('start not found');
const setSavingIndex = text.indexOf('    setSaving(false)', start);
if (setSavingIndex === -1) throw new Error('setSaving not found');
const blockEndMarker = '\n  }\n';
const blockEnd = text.indexOf(blockEndMarker, setSavingIndex);
if (blockEnd === -1) throw new Error('block end not found');
const replaceEnd = blockEnd + blockEndMarker.length;
const newBlockLines = [
  '    const tagsArray = values.tags',
  '      .split(,)',
  '      .map((tag) => tag.trim())',
  '      .filter(Boolean)',
  '    const payload = {',
  '      slug: values.slug.trim(),',
  '      title: values.title.trim(),',
  '      excerpt: values.excerpt || null,',
  '      meta_title: values.meta_title || null,',
  '      meta_description: values.meta_description || null,',
  '      meta_keywords: values.meta_keywords || null,',
  '      og_title: values.og_title || null,',
  '      og_description: values.og_description || null,',
  '      og_image: values.og_image || null,',
  '      cover_image: values.cover_image || null,',
  '      author_name: values.author_name || null,',
  '      author_avatar: values.author_avatar || null,',
  '      category: values.category || null,',
  '      tags: tagsArray.length ? tagsArray : null,',
  '      reading_time: values.reading_time ? Number(values.reading_time) : null,',
  '      published: values.published,',
  '    }',
  ' ',
  '    try {',
  '      let postId: string | undefined = editing?.id',
  ' ',
  '      if (editing) {',
  '        const { error } = await supabase',
  '          .from( posts)',
  '          .update(payload)',
  '          .eq(id, editing.id)',
  ' ',
  '        if (error) throw error',
  '      } else {',
  '        const { data, error } = await supabase',
  '          .from(posts)',
  '          .insert([payload])',
  '          .select(id)',
  ' ',
  '        if (error) throw error',
  '        postId = data?.[0]?.id',
  '      }',
  ' ',
  '      if (postId) {',
  '        const sectionsPayload = values.sections.map((section, index) => ({',
  '          post_id: postId,',
  '          title: section.title || null,',
  '          content: section.content || null,',
  '          image_url: section.image_url.trim(),',
  '          alt_text: section.alt_text || null,',
  '          caption: section.caption || null,',
  '          image_order: index,',
  '        }))',
  ' ',
  '        if (editing) {',
  '          const { error: deleteError } = await supabase',
  '            .from(post_images)',
  '            .delete()',
  '            .eq(post_id, postId)',
  ' ',
  '          if (deleteError) throw deleteError',
  '        }',
  ' ',
  '        if (sectionsPayload.length) {',
  '          const { error: sectionsError } = await supabase',
  '            .from(post_images)',
  '            .insert(sectionsPayload)',
  ' ',
  '          if (sectionsError) throw sectionsError',
  '        }',
  ' ',
  '        await fetchPosts()',
  '      }',
  ' ',
  '      setFormOpen(false)',
  '      setEditing(null)',
  '    } catch (err: any) {',
  '      alert(err.message)',
  '    }',
  ' ',
  '    setSaving(false)',
  '  }',
];
const newBlock = newBlockLines.join('\n') + '\n';
text = text.slice(0, start) + newBlock + text.slice(replaceEnd);
fs.writeFileSync(path, text, 'utf8');
